def raw_page_map() -> dict[str, list[str]]:
    payload = json.loads((ROOT / "catalogs.search-overrides.json").read_text(encoding="utf-8"))
    page_map = payload[CATALOG_ID]
    assert isinstance(page_map, dict)
    return page_map


def test_fredi_manual_search_override_covers_every_pdf_page() -> None:
    page_map = raw_page_map()

    assert set(page_map) == {str(page) for page in range(1, 56)}
    assert all(isinstance(terms, list) and terms for terms in page_map.values())
    assert all(len(terms) == len(set(terms)) for terms in page_map.values())

    loaded = load_manual_search_overrides(ROOT)[CATALOG_ID]
    assert set(loaded) == set(range(1, 56))
    assert all(loaded[page].strip() for page in range(1, 56))


def test_fredi_models_and_verified_product_specs_are_locked() -> None:
    page_map = raw_page_map()

    for page, model in PAGE_MODELS.items():
        terms = set(page_map[str(page)])
        assert model in terms, f"page {page} lost model {model}"
        assert f"חדר שינה {model}" in terms, f"page {page} lost model search phrase"
        assert VERIFIED_PRODUCT_TERMS[page].issubset(terms), f"page {page} lost verified product terms"


def test_fredi_manual_only_search_keeps_all_pages_after_ocr_is_disabled() -> None:
    manual_pages = load_manual_search_overrides(ROOT)[CATALOG_ID]
    merged = merge_manual_search_pages([], manual_pages, page_count=55)

    assert [page["page"] for page in merged] == list(range(1, 56))
    for page in merged:
        page_number = page["page"]
        text = page["text"]
        assert PAGE_MODELS[page_number] in text
        for term in VERIFIED_PRODUCT_TERMS[page_number]:
            assert term in text


def test_fredi_manual_search_excludes_repeated_legal_and_delivery_noise() -> None:
    page_map = raw_page_map()

    for page, terms in page_map.items():
        joined = " ".join(terms)
        for fragment in RECURRING_JUNK:
            assert fragment not in joined, f"page {page} contains recurring non-search text: {fragment}"
